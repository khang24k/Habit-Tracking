export function getCategoryLabel(key: CategoryKey, locale: Locale): string {
  return CATEGORY_LABELS[locale][key] ?? key;
}

export function getPriorityLabel(key: PriorityKey, locale: Locale): string {
  return PRIORITY_LABELS[locale][key] ?? key;
}

export function getFrequencyLabel(key: FrequencyKey, locale: Locale): string {
  return FREQUENCY_LOCALE_LABELS[locale][key] ?? key;
}

export function getHabitColorLabel(key: HabitColorKey, locale: Locale): string {
  return HABIT_COLOR_LABELS[locale][key] ?? key;
}

export function getHabitTemplates(locale: Locale): HabitTemplate[] {
  return HABIT_TEMPLATES_LOCALE[locale];
}

